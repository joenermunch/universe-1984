import { describe, expect, it } from "vitest";
import { FRAGMENTS } from "../../src/library/fragments.ts";
import { Builder } from "../../src/universe/build.ts";
import { Planner } from "../../src/planner/planner.ts";
import { parse } from "../../src/sexpr.ts";
import type { Person, World } from "../../src/model/world.ts";
import { fixture } from "./helpers.ts";

/** Find, in a generated universe, the setting L90 describes: a married woman, her lover, and a living father-in-law. */
function setting(w: World): { her: Person; him: Person; husband: Person; parent: Person } | null {
  for (const her of w.persons.values()) {
    if (her.sex !== "F" || !w.alive(her) || !w.isAdult(her)) continue;
    const husband = w.spouse(her);
    const parent = husband && w.parentsOf(husband).find((p) => w.alive(p));
    if (!husband || !parent) continue;
    const him = [...w.persons.values()].find((p) => p.sex === "M" && w.alive(p) && w.isAdult(p) && w.available(p) && !w.directlyRelated(p, her) && p.id !== parent.id);
    if (him) return { her, him, husband, parent };
  }
  return null;
}

describe("L90 automatic outline (Nadine/Steven) on a generated cast", () => {
  it("follows forced-marriage, eliminates by EXPOSE in two events, then churns further", () => {
    const fx = fixture("outline-1990-nadine-steven.json");
    let tested = 0;
    for (let seed = 1; seed <= 60 && tested < 5; seed++) {
      const w = new Builder({ seed }).build();
      const s = setting(w);
      if (!s) continue;
      tested++;
      // the "setting generated by the program" (L90): lovers; father-in-law "none too nice a guy"
      s.parent.modifiers.niceness = -7 - (w.base(s.parent, "niceness") ?? 0);
      s.her.modifiers.promiscuity = 7 - (w.base(s.her, "promiscuity") ?? 5);
      for (const [a, b] of [[s.her, s.him], [s.him, s.her]] as const) { w.setIpr(a, b, "pos-neg", 8); w.setIpr(a, b, "attract", 8); }
      w.setTogether(s.her, s.him, true);
      s.her.symbol = "HER"; s.him.symbol = "HIM";
      const p = new Planner(w, FRAGMENTS, {
        seed, version: "U90", names: "full", budget: 40,
        script: { "fragment:churn": ["FORCED-MARRIAGE", "EX-ATTEMPT"], "fragment:eliminate": "EXPOSE", "fragment:together": "SEDUCTION" },
      });
      let outline: string[];
      try { outline = p.tell([parse("(churn him her)")]).outline; }
      catch (e) { if (/choice script/.test(String(e))) { tested--; continue; } throw e; } // this cast cannot follow the L90 path
      const N = (x: Person) => w.fullName(x);
      const [H, L, HU, P] = [N(s.her), N(s.him), N(s.husband), N(s.parent)];
      expect(outline[0]).toBe(`${P} threatens ${H}: forget it.`);
      expect(outline[1]).toBe(`${H} tells ${L} that she doesn't love him.`);
      expect(outline[2]).toMatch(new RegExp(`^.+ is worried about ${L}\\.$`));
      // either direction is documented: L90 "Linda … seduces Steven"; L85-TR Fig. 10 "RENEE seduces ROMAN" (the lover seduces)
      const l3 = outline[3] ?? "";
      expect(l3.startsWith(`${L} seduces `) || l3.endsWith(` seduces ${L}.`), l3).toBe(true);
      expect(outline[4]).toMatch(new RegExp(`^(.+) decides to expose ${P}\\.$`));
      expect(outline[5]).toMatch(new RegExp(`^.+ tells the world about ${P}\\.$`));
      expect(outline[6]).toBe(`${H} and ${HU} get divorced.`);
      expect(outline.slice(7, 10)).toEqual([`${HU} tries to seduce ${H}.`, `${L} gets frustrated.`, `${L} tells ${H} that he doesn't love her.`]);
      expect([`${H} seduces ${L}.`, `${L} seduces ${H}.`]).toContain(outline[10]); // L90: "Nadine … seduces Steven"; direction is a random binding
      // same shape as the published outline: 11 events
      expect(outline.length).toBe(fx.outline.length);
    }
    expect(tested).toBeGreaterThan(0);
  });
});
